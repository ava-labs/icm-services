#!/usr/bin/env bash
set -euo pipefail

# Nightly ZK integration test
#
# Sends a message on Ethereum, waits until a finalized checkpoint covers the transaction, and
# proves the message against that checkpoint.
#
# TODO: Also prove the checkpoint with an SP1 Helios consensus proof once a proof source exists.
# Until then the e2e test trusts the checkpoint as the ZKAdapter's starting state.
# Issue: https://github.com/ava-labs/icm-services/issues/1627
#
# Required env vars:
#   ETH_RPC_URL        - Ethereum execution layer RPC
#   SENDER_PRIVATE_KEY - Private key for the funded Ethereum account
#   SENDER_CONTRACT    - Address of the ECDSAVerifier on Ethereum
#   BEACON_API_URL     - Ethereum beacon API endpoint

: "${ETH_RPC_URL:?Set ETH_RPC_URL to a Ethereum execution RPC}"
: "${SENDER_PRIVATE_KEY:?Set SENDER_PRIVATE_KEY to a funded Ethereum private key}"
: "${SENDER_CONTRACT:?Set SENDER_CONTRACT to the ECDSAVerifier address on Ethereum}"
: "${BEACON_API_URL:?Set BEACON_API_URL to a Ethereum beacon API}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
FIXTURE_DIR="$SCRIPT_DIR/tools/fixture-gen"
TESTDATA="$ROOT_DIR/tests/testdata/nightly"
mkdir -p "$TESTDATA"

echo " ******************************"
echo "  Nightly ZK Integration Test"
echo " ******************************"
echo ""

# Build Docker image
echo "Building Docker image." 
docker build -t fixture-gen "$FIXTURE_DIR"
echo ""

# Send message on Ethereum
echo " Sending message from ECDSAVerifier contract on Ethereum"
docker run --rm \
  -e ETH_RPC_URL="$ETH_RPC_URL" \
  -e SENDER_PRIVATE_KEY="$SENDER_PRIVATE_KEY" \
  -e SENDER_CONTRACT="$SENDER_CONTRACT" \
  -v "$TESTDATA:/app/testdata" \
  fixture-gen node send_ethereum_message.mts

TX_HASH=$(jq -r '.txHash' "$TESTDATA/tx_info.json")
echo "Transaction hash: $TX_HASH"
echo ""

# Wait for a finalized checkpoint after the transaction to anchor it
echo "Waiting for a finalized checkpoint after the transaction"
docker run --rm \
  -e BEACON_API_URL="$BEACON_API_URL" \
  -e ETH_RPC_URL="$ETH_RPC_URL" \
  -e TX_HASH="$TX_HASH" \
  -v "$TESTDATA:/app/testdata" \
  fixture-gen node wait_for_finality.mts # writes nightly/anchor.json

ANCHOR_SLOT=$(jq -r '.anchorSlot' "$TESTDATA/anchor.json")
echo ""
echo " ******************************"
echo "  Transaction finalized successfully"
echo "  TX hash:     $TX_HASH"
echo "  Anchor slot: $ANCHOR_SLOT"
echo "  Fixtures:    $TESTDATA"
echo " ******************************"

# Generate Ethereum SSZ/MPT proofs against the finalized beacon state for receipt log inclusion
echo "=== Step 4: Generating Ethereum receipt log inclusion proofs ==="
LOG_INDEX=$(jq -r '.logIndex' "$TESTDATA/tx_info.json")
docker run --rm \
  -e BEACON_API_URL="$BEACON_API_URL" \
  -e ETH_RPC_URL="$ETH_RPC_URL" \
  -e TX_HASH="$TX_HASH" \
  -e LOG_INDEX="$LOG_INDEX" \
  -e ANCHOR_SLOT="$ANCHOR_SLOT" \
  -v "$TESTDATA:/app/testdata" \
  fixture-gen node --max-old-space-size=8192 generate_fixture.mts # writes nightly/ethereum_fixture.json 
echo ""

# Run Go e2e test
echo "=== Step 5: Running Go e2e test ==="
cd "$ROOT_DIR"
ETHEREUM_FIXTURE_PATH="$TESTDATA/ethereum_fixture.json" \
GINKGO_FOCUS="ZKAdapter" ./scripts/e2e_test.sh --components ethereum-icm-verification

# Verify the relayer's Go proof pipeline reproduces the fixture just generated by lodestar
echo "=== Step 6: Verifying Go execution proof pipeline against the fixture ==="
BEACON_API_URL="$BEACON_API_URL" \
ETHEREUM_FIXTURE_PATH="$TESTDATA/ethereum_fixture.json" \
go test ./messages/zk/proofs/ -run Integration -timeout 15m -v

echo ""
echo " ******************************"
echo "  Nightly ZK Integration Test PASSED!"
echo " ******************************"
